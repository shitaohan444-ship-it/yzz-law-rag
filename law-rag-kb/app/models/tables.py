kb_document = Table(
    "kb_document",
    Base.metadata,
    Column("id", BigInteger, primary_key=True),
    Column("doc_title", String(255)),
    Column("doc_type", String(80)),
    Column("legal_category", String(100)),
    Column("category_id", BigInteger),
    Column("source_department_id", BigInteger),
    Column("author_employee_id", BigInteger),
    Column("attachment_id", BigInteger),
    Column("content_text", Text),
    Column("description_summary", Text),  # LLM 生成的文档级中文摘要（Markdown 渲染端点用）
    Column("body_markdown", Text),  # 文档转成的规范 Markdown 全文（含 #img:{image_id} 占位）
    Column("embedding_status", String(50)),
    Column("permission_level", String(50)),
    Column("source_type", String(32)),
    Column("biz_type", String(50)),
    Column("biz_id", BigInteger),
    Column("case_id", BigInteger),
    Column("dossier_no", String(100)),
    Column("extra_metadata", JSON),
    Column("effective_status", String(20)),
    Column("effective_from", Date),
    Column("effective_to", Date),
    Column("cause_codes", JSON),
    Column("upload_timings", JSON),
    Column("ingest_timings", JSON),
    Column("vl_status", String(32)),
    Column("image_total", Integer),
    Column("image_kept", Integer),
    Column("image_filtered", Integer),
    Column("vl_processed_at", DateTime(timezone=True)),
    Column("remark", String(500)),  # 入库失败时写截断错误
    Column("created_by", BigInteger),
    Column("updated_at", DateTime(timezone=True)),
    Column("deleted_at", DateTime(timezone=True)),
    Column("status", String(50)),
    schema="oa",
    extend_existing=True,
)

